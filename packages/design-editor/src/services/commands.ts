/** Deletes whatever is selected. */
export function deleteSelection(): void {
  const view = useView.getState();
  const doc = useDocument.getState();
  const { selection } = view;
  if (selection.kind === 'elements') {
    if (edit(selection.board, { kind: 'remove', targets: selection.items.map(({ tid, path }) => ({ tid, path })) })) {
      view.select(NO_SELECTION);
      announce(selection.items.length === 1 ? 'Deleted' : `Deleted ${selection.items.length} elements`);
    }
  } else if (selection.kind === 'objects') {
    // Locked artboards and notes stay; only an all-locked selection is refused.
    const free = unlockedObjects(doc.canvas, selection.boards, selection.notes);
    if (!free.boards.length && !free.notes.length) {
      if (anyLockedObject(doc.canvas, selection.boards, selection.notes)) refuseLocked();
      return;
    }
    if (free.notes.length) {
      doc.updateCanvas((canvas) => {
        const notes = { ...canvas.notes };
        for (const id of free.notes) delete notes[id];
        return { ...canvas, notes };
      });
    }
    if (free.boards.length) doc.deleteBoards(free.boards);
    const kept = selection.boards.length + selection.notes.length - free.boards.length - free.notes.length;
    view.select(kept ? { kind: 'objects', boards: selection.boards.filter((path) => !free.boards.includes(path)), notes: selection.notes.filter((id) => !free.notes.includes(id)) } : NO_SELECTION);
    const count = free.notes.length + free.boards.length;
    announce(count === 1 ? 'Deleted' : `Deleted ${count} items`);
  }
}

/** Duplicates the selection next to itself. */
export function duplicateSelection(): void {
  const view = useView.getState();
  const doc = useDocument.getState();
  const { selection } = view;
  if (selection.kind === 'elements') {
    edit(selection.board, { kind: 'duplicate', targets: selection.items.map(({ tid, path }) => ({ tid, path })) }, { selectCreated: true });
    return;
  }
  if (selection.kind !== 'objects') return;
  const taken = new Set([...Object.keys(doc.boards), ...Object.keys(doc.canvas.boards)]);
  const newBoards: string[] = [];
  for (const path of selection.boards) {
    const entry = doc.canvas.boards[path];
    const source = doc.boards[path]?.source;
    if (!entry || !source) continue;
    const name = freeBoardName(path.replace(/\.dc\.html$/, '').replace(/^.*\//, ''), taken);
    taken.add(name);
    useDocument.getState().createBoard(name, source, { ...withoutLock(entry), x: entry.x + entry.w + 80 });
    newBoards.push(name);
  }
  let newNotes: string[] = [];
  if (selection.notes.length) {
    useDocument.getState().updateCanvas((canvas) => {
      // Copies of a group form a new group of their own; copies start unlocked.
      const sources = selection.notes.flatMap((id) => (canvas.notes[id] ? [canvas.notes[id]!] : []));
      const copied = addNoteCopies(canvas, sources, (note) => ({ ...withoutLock(note), x: note.x + 24, y: note.y + 24 }));
      newNotes = copied.ids;
      return copied.canvas;
    });
  }
  view.select({ kind: 'objects', boards: newBoards, notes: newNotes });
}

/* ------------------------------ note groups ----------------------------- */

/**
 * Groups (⌘G) or ungroups (⇧⌘G) the selected canvas notes. Only objects
 * outside artboards group; a refusal is shown as a toast.
 */
export function groupSelectedNotes(kind: 'group' | 'ungroup'): void {
  const doc = useDocument.getState();
  const { selection } = useView.getState();
  if (doc.readOnly || selection.kind !== 'objects') return;
  if (selection.boards.length) {
    toast.add({ title: 'Group and Ungroup work only on objects outside artboards. Select only those.' });
    return;
  }
  if (anyLockedObject(doc.canvas, [], selection.notes)) {
    refuseLocked();
    return;
  }
  const next = regroupNotes(doc.canvas, selection.notes, kind, freshGroupId(doc.canvas));
  if ('refused' in next) {
    toast.add({ title: groupRefusalMessage(next.refused) });
    return;
  }
  doc.updateCanvas(() => next.canvas);
}

/**
 * Moves the selected artboards, notes or elements one step or to the end of
 * the stack and says what happened. Artboards stack in `order` (back to
 * front on each page); artboards and notes move together, as one undo step.
 * Locked ones stay. Returns false when nothing selected stacks.
 */
export function stackSelection(order: StackOrder): boolean {
  const doc = useDocument.getState();
  const { selection } = useView.getState();
  if (selection.kind === 'objects' && selection.boards.length + selection.notes.length) {
    if (doc.readOnly) return true;
    const free = unlockedObjects(doc.canvas, selection.boards, selection.notes);
    if (!free.boards.length && !free.notes.length) {
      refuseLocked();
      return true;
    }
    let next = restackBoards(doc.canvas, free.boards, order);
    if (free.notes.length) next = order === 'forward' || order === 'backward' ? stepNotes(next, free.notes, order) : restackNotes(next, free.notes, order);
    if (next !== doc.canvas) doc.updateCanvas(() => next);
    announce(stackMessage(order, next !== doc.canvas));
    return true;
  }
  if (selection.kind !== 'elements' || doc.readOnly) return false;
  const result = reorderSelection(stacksUp(order) ? 1 : -1, order === 'front' || order === 'back');
  if (result) announce(stackMessage(order, result === 'moved'));
  return true;
}

/** Whether ⌘G / ⇧⌘G would group or ungroup the selected notes. */
export function noteGroupingFor(kind: 'group' | 'ungroup'): boolean {
  const { canvas } = useDocument.getState();
  const { selection } = useView.getState();
  if (selection.kind !== 'objects' || selection.boards.length || !selection.notes.length) return false;
  const items = groupItems(canvas);
  return kind === 'group' ? planGroup(items, selection.notes, '') instanceof Map : selectionHasGroup(items, selection.notes);
}

/** Wraps the selected elements in a flex or grid container. */
export function wrapSelection(display: 'flex' | 'grid' | 'block'): void {
  const selected = selectedAddresses();
  if (!selected) return;
  const style = display === 'flex' ? 'display: flex; gap: 8px;' : display === 'grid' ? 'display: grid; grid-template-columns: repeat(2, 1fr); gap: 8px;' : '';
  edit(selected.board, { kind: 'wrap', targets: selected.targets, open: style ? `<div style="${style}">` : '<div>', close: '</div>' }, { selectCreated: true });
}

/** Removes the selected container, keeping its children. */
export function unwrapSelection(): void {
  const selected = selectedAddresses();
  if (!selected || selected.targets.length !== 1) return;
  if (edit(selected.board, { kind: 'unwrap', target: selected.targets[0]! })) useView.getState().select(NO_SELECTION);
}

/** The selected elements of one artboard, outermost only, in document order. */
export function selectedElements(): { board: string; model: TemplateModel; elements: HtmlElement[] } | null {
  const { selection } = useView.getState();
  if (selection.kind !== 'elements' || selection.items.length === 0) return null;
  const source = useDocument.getState().boards[selection.board]?.source;
  if (!source) return null;
  const model = templateOf(source);
  const resolved = selection.items.map((item) => resolveElement(model, item.tid, item.path)).filter((el): el is HtmlElement => Boolean(el));
  const inside = (outer: HtmlElement, inner: HtmlElement) => outer !== inner && outer.start <= inner.start && inner.end <= outer.end;
  const elements = resolved.filter((el) => !resolved.some((other) => inside(other, el))).sort((a, b) => a.start - b.start);
  return elements.length ? { board: selection.board, model, elements } : null;
}

const addressIn = (model: TemplateModel, element: HtmlElement): Address => ({ tid: model.tidOf.get(element)!, path: elementPath(model, element) });

/** Siblings of an element (template children of its parent, or the top level). */
function siblingsOf(model: TemplateModel, element: HtmlElement): HtmlElement[] {
  return (element.parent ? elementChildren(element.parent) : elementChildren(model.nodes)).filter((el) => el.tag !== 'helmet');
}

/**
 * Moves the selection one step (`toEnd` false: before its previous / after
 * its next sibling) or to the first / last place among its siblings.
 */
export function reorderSelection(direction: -1 | 1, toEnd = false): 'moved' | 'end' | null {
  const plan = reorderPlan(direction, toEnd);
  if (!plan || plan === 'end') return plan;
  return edit(plan.board, plan.op, { selectCreated: true }) ? 'moved' : null;
}

/** The move `reorderSelection` would make: `'end'` when already there, `null` when it can't. */
function reorderPlan(direction: -1 | 1, toEnd: boolean): { board: string; op: BoardOp } | 'end' | null {
  const selected = selectedElements();
  if (!selected) return null;
  const { model } = selected;
  // A shape that is its graphic's only layer stacks as the graphic.
  const elements = [...new Set(selected.elements.map(layerOf))].sort((a, b) => a.start - b.start);
  const parent = elements[0]!.parent;
  if (elements.some((el) => el.parent !== parent)) return null;
  const siblings = siblingsOf(model, elements[0]!);
  const others = siblings.filter((el) => !elements.includes(el));
  if (!others.length) return 'end';
  let neighbour: HtmlElement | undefined;
  if (toEnd) neighbour = direction > 0 ? others[others.length - 1] : others[0];
  else if (direction > 0) neighbour = siblings.slice(siblings.indexOf(elements[elements.length - 1]!) + 1).find((el) => !elements.includes(el));
  else neighbour = siblings.slice(0, siblings.indexOf(elements[0]!)).reverse().find((el) => !elements.includes(el));
  if (!neighbour) return 'end';
  // Already at that end.
  if (toEnd && (direction > 0 ? neighbour.start < elements[0]!.start : neighbour.start > elements[elements.length - 1]!.start)) return 'end';
  return { board: selected.board, op: { kind: 'move', targets: elements.map((el) => addressIn(model, el)), target: addressIn(model, neighbour), position: direction < 0 ? 'before' : 'after' } };
}

/**
 * Whether the selection can go `order`'s way in the stack: `false` when it
 * is already at that end, `null` when it has nothing that stacks.
 */
export function stackRoom(order: StackOrder): boolean | null {
  const { canvas } = useDocument.getState();
  const { selection } = useView.getState();
  if (selection.kind === 'objects' && selection.boards.length + selection.notes.length) {
    const free = unlockedObjects(canvas, selection.boards, selection.notes);
    if (!free.boards.length && !free.notes.length) return null;
    let next = restackBoards(canvas, free.boards, order);
    if (free.notes.length) next = order === 'forward' || order === 'backward' ? stepNotes(next, free.notes, order) : restackNotes(next, free.notes, order);
    return next !== canvas;
  }
  if (selection.kind !== 'elements') return null;
  const plan = reorderPlan(stacksUp(order) ? 1 : -1, order === 'front' || order === 'back');
  return plan === null ? null : plan !== 'end';
}

/** Selects every sibling of the selected element that is not locked (⌘A inside an artboard). */
export function selectAllSiblings(): void {
  const selected = selectedElements();
  if (!selected) return;
  const { model, elements, board } = selected;
  const items = siblingsOf(model, elements[0]!)
    .filter((el) => !isElementLocked(el))
    .map((el) => ({ ...addressIn(model, el), instance: 0 }));
  if (items.length) useView.getState().select({ kind: 'elements', board, items });
}

