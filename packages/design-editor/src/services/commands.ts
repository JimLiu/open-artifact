/**
 * Groups (⌘G) or ungroups (⇧⌘G) the selected canvas notes. Only objects
 * outside artboards group; a refusal is shown as a toast.
 */
export function groupSelectedNotes(kind: 'group' | 'ungroup'): void {
  const doc = useDocument.getState();
  const { selection } = useView.getState();
  if (doc.readOnly || selection.kind !== 'objects') return;
  if (selection.boards.length) {
    toast.add({ title: 'Group and Ungroup work only on objects outside artboards. Select only those.' });
    return;
  }
  if (anyLockedObject(doc.canvas, [], selection.notes)) {
    refuseLocked();
    return;
  }
  const next = regroupNotes(doc.canvas, selection.notes, kind, freshGroupId(doc.canvas));
  if ('refused' in next) {
    toast.add({ title: groupRefusalMessage(next.refused) });
    return;
  }
  doc.updateCanvas(() => next.canvas);
}

/**
 * Moves the selected artboards, notes or elements one step or to the end of
 * the stack and says what happened. Artboards stack in `order` (back to
 * front on each page); artboards and notes move together, as one undo step.
 * Locked ones stay. Returns false when nothing selected stacks.
 */
export function stackSelection(order: StackOrder): boolean {
  const doc = useDocument.getState();
  const { selection } = useView.getState();
  if (selection.kind === 'mixed') {
    stackMixed(selection, order);
    return true;
  }
  if (selection.kind === 'objects' && selection.boards.length + selection.notes.length) {
    if (doc.readOnly) return true;
    const free = unlockedObjects(doc.canvas, selection.boards, selection.notes);
    if (!free.boards.length && !free.notes.length) {
      refuseLocked();
      return true;
    }
    const next = restackObjects(doc.canvas, free.boards, free.notes, order);
    if (next !== doc.canvas) doc.updateCanvas(() => next);
    announce(stackMessage(order, next !== doc.canvas));
    return true;
  }
  if (selection.kind !== 'elements' || doc.readOnly) return false;
  const result = reorderSelection(stacksUp(order) ? 1 : -1, order === 'front' || order === 'back');
  if (result) announce(stackMessage(order, result === 'moved'));
  return true;
}

/** Whether ⌘G / ⇧⌘G would group or ungroup the selected notes. */
export function noteGroupingFor(kind: 'group' | 'ungroup'): boolean {
  const { canvas } = useDocument.getState();
  const { selection } = useView.getState();
  if (selection.kind !== 'objects' || selection.boards.length || !selection.notes.length) return false;
  const items = groupItems(canvas);
  return kind === 'group' ? planGroup(items, selection.notes, '') instanceof Map : selectionHasGroup(items, selection.notes);
}

