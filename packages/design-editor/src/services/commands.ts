/** The selected elements of one artboard, outermost only, in document order. */
export function selectedElements(): ResolvedGroup | null {
  const { selection } = useView.getState();
  if (selection.kind !== 'elements' || selection.items.length === 0) return null;
  return resolveGroup(selection);
}

/** Selected elements of one artboard resolved in its source: outermost only, in document order. */
export interface ResolvedGroup {
  board: string;
  model: TemplateModel;
  elements: HtmlElement[];
}

function resolveGroup(group: BoardElements): ResolvedGroup | null {
  const source = useDocument.getState().boards[group.board]?.source;
  if (!source) return null;
  const model = templateOf(source);
  const resolved = group.items.map((item) => resolveElement(model, item.tid, item.path)).filter((el): el is HtmlElement => Boolean(el));
  const inside = (outer: HtmlElement, inner: HtmlElement) => outer !== inner && outer.start <= inner.start && inner.end <= outer.end;
  const elements = resolved.filter((el) => !resolved.some((other) => inside(other, el))).sort((a, b) => a.start - b.start);
  return elements.length ? { board: group.board, model, elements } : null;
}

/** Each artboard's selected elements, resolved (see `resolveGroup`). */
export function resolvedGroups(groups: readonly BoardElements[]): ResolvedGroup[] {
  return groups.map(resolveGroup).filter((group): group is ResolvedGroup => group !== null);
}

const addressIn = (model: TemplateModel, element: HtmlElement): Address => ({ tid: model.tidOf.get(element)!, path: elementPath(model, element) });

/** Siblings of an element (template children of its parent, or the top level). */
function siblingsOf(model: TemplateModel, element: HtmlElement): HtmlElement[] {
  return (element.parent ? elementChildren(element.parent) : elementChildren(model.nodes)).filter((el) => el.tag !== 'helmet');
}

/**
 * Moves the selection one step (`toEnd` false: before its previous / after
 * its next sibling) or to the first / last place among its siblings.
 */
export function reorderSelection(direction: -1 | 1, toEnd = false): 'moved' | 'end' | null {
  const selected = selectedElements();
  // One locked element holds the whole selection back.
  if (selected && selected.elements.some((el) => isElementLocked(el) || isElementLocked(layerOf(el)))) {
    refuseLocked();
    return null;
  }
  const plan = reorderPlan(direction, toEnd, selected);
  if (!plan || plan === 'end') return plan;
  // Runs apart in the list move one step each, as one undo step.
  let done = false;
  let refused = null as EditOutcome | null;
  useDocument.getState().transact(() => {
    for (const op of plan.ops) {
      const outcome = tryEdit(plan.board, op);
      if (outcome.kind === 'done') done = true;
      else refused ??= outcome;
    }
  });
  if (!done) {
    if (refused?.kind === 'locked') refuseLocked();
    else if (refused?.kind === 'failed') toast.add({ title: 'That edit does not apply here', description: 'The element is generated by code. Ask the agent to change it.' });
    return null;
  }
  // Every selected element stays selected, the ones at the end already too.
  const source = useDocument.getState().boards[plan.board]?.source;
  const model = source ? templateOf(source) : null;
  const parent = plan.parent === null ? null : model?.elements[plan.parent];
  const siblings = model ? (parent ? elementChildren(parent) : elementChildren(model.nodes)).filter((el) => el.tag !== 'helmet') : [];
  const items = model ? plan.picked.flatMap((at) => (siblings[at] ? [{ ...addressIn(model, siblings[at]!), instance: 0 }] : [])) : [];
  if (items.length) useView.getState().select({ kind: 'elements', board: plan.board, items });
  return 'moved';
}

/**
 * The moves `reorderSelection` would make: `'end'` when already there, `null` when it can't. A step moves
 * each run of selected siblings past the sibling next to it (a, c of a b c d forward: b a d c), so runs apart
 * are one move each, last first: a move changes nothing before it, so the addresses of the others still hold.
 */
function reorderPlan(direction: -1 | 1, toEnd: boolean, selected: ResolvedGroup | null = selectedElements()): ReorderPlan | 'end' | null {
  if (!selected) return null;
  const { model } = selected;
  // A shape that is its graphic's only layer stacks as the graphic.
  const elements = [...new Set(selected.elements.map(layerOf))].sort((a, b) => a.start - b.start);
  const parent = elements[0]!.parent;
  if (elements.some((el) => el.parent !== parent)) return null;
  const siblings = siblingsOf(model, elements[0]!);
  const others = siblings.filter((el) => !elements.includes(el));
  if (!others.length) return 'end';
  const position: InsertPosition = direction < 0 ? 'before' : 'after';
  const moveOp = (run: HtmlElement[], neighbour: HtmlElement): BoardOp => ({ kind: 'move', targets: run.map((el) => addressIn(model, el)), target: addressIn(model, neighbour), position });
  // The order the siblings end in, worked out along with the moves.
  const order = [...siblings];
  const place = (run: HtmlElement[], neighbour: HtmlElement) => {
    const rest = order.filter((el) => !run.includes(el));
    const at = rest.indexOf(neighbour) + (direction > 0 ? 1 : 0);
    order.splice(0, order.length, ...rest.slice(0, at), ...run, ...rest.slice(at));
  };
  const plan = (ops: BoardOp[]): ReorderPlan => ({
    board: selected.board,
    ops,
    parent: parent ? model.tidOf.get(parent)! : null,
    picked: elements.map((el) => order.indexOf(el)),
  });
  if (toEnd) {
    const neighbour = direction > 0 ? others[others.length - 1]! : others[0]!;
    // Already at that end.
    if (direction > 0 ? neighbour.start < elements[0]!.start : neighbour.start > elements[elements.length - 1]!.start) return 'end';
    place(elements, neighbour);
    return plan([moveOp(elements, neighbour)]);
  }
  // Runs of selected siblings with nothing unselected between them.
  const runs: HtmlElement[][] = [];
  let previous = -2;
  for (const el of elements) {
    const at = siblings.indexOf(el);
    if (at === previous + 1) runs[runs.length - 1]!.push(el);
    else runs.push([el]);
    previous = at;
  }
  const ops: BoardOp[] = [];
  for (const run of runs) {
    const neighbour = siblings[direction > 0 ? siblings.indexOf(run[run.length - 1]!) + 1 : siblings.indexOf(run[0]!) - 1];
    if (neighbour) {
      ops.push(moveOp(run, neighbour));
      place(run, neighbour);
    }
  }
  if (!ops.length) return 'end';
  return plan(ops.reverse());
}

/** The moves of a restack, the parent they happen in (`null`: the top level) and where the selected end up. */
interface ReorderPlan {
  board: string;
  ops: BoardOp[];
  parent: number | null;
  picked: number[];
}

/**
 * Whether the selection can go `order`'s way in the stack: `false` when it
 * is already at that end, `null` when it has nothing that stacks.
 */
export function stackRoom(order: StackOrder): boolean | null {
  const { canvas } = useDocument.getState();
  const { selection } = useView.getState();
  if (selection.kind === 'mixed') return mixedStackRoom(selection, order);
  if (selection.kind === 'objects' && selection.boards.length + selection.notes.length) {
    const free = unlockedObjects(canvas, selection.boards, selection.notes);
    if (!free.boards.length && !free.notes.length) return null;
    return restackObjects(canvas, free.boards, free.notes, order) !== canvas;
  }
  if (selection.kind !== 'elements') return null;
  const plan = reorderPlan(stacksUp(order) ? 1 : -1, order === 'front' || order === 'back');
  return plan === null ? null : plan !== 'end';
}

/** Selects every sibling of the selected element that is not locked (⌘A inside an artboard). */
export function selectAllSiblings(): void {
  const selected = selectedElements();
  if (!selected) return;
  const { model, elements, board } = selected;
  const items = siblingsOf(model, elements[0]!)
    .filter((el) => !isElementLocked(el))
    .map((el) => ({ ...addressIn(model, el), instance: 0 }));
  if (items.length) useView.getState().select({ kind: 'elements', board, items });
}

/* -------------------------------- moving -------------------------------- */

const round = (value: number): string => `${Math.round(value * 100) / 100}px`;

/**
 * Moves absolutely positioned elements by an offset in artboard pixels,
 * through `left`/`top` (or `right`/`bottom` when only those are set).
 * Locked elements stay (with a toast when all of them are locked).
 * Returns `false` when any selected element is in the flow.
 */
export function moveSelectedElements(dx: number, dy: number, options: { coalesce?: string } = {}): boolean {
  const selected = selectedElements();
  if (!selected) return false;
  const plan = elementMoveEdits(selected, dx, dy);
  if (plan === 'locked') refuseLocked();
  if (typeof plan === 'string' || !plan.length) return false;
  return edit(selected.board, { kind: 'styles', edits: plan }, { coalesce: options.coalesce });
}

/**
 * The style edits that move one artboard's selected elements: `'locked'`
 * when all are locked, `'flow'` when one of the free ones is in the flow.
 */
function elementMoveEdits(selected: ResolvedGroup, dx: number, dy: number, options: { locked?: boolean } = {}): { target: Address; patch: StylePatch }[] | 'locked' | 'flow' {
  // A copy's placement comes from every original, locked ones included.
  const free = options.locked ? selected.elements : selected.elements.filter((element) => !isElementLocked(element));
  if (!free.length) return 'locked';
  const api = boardApi(selected.board);
  const edits: { target: Address; patch: StylePatch }[] = [];
  for (const element of free) {
    const inline = styleMap(attributeValue(element, 'style') ?? '');
    const tid = selected.model.tidOf.get(element)!;
    const computed = api?.inspect(tid)?.computed ?? {};
    const position = inline.position || computed.position || '';
    if (position !== 'absolute' && position !== 'fixed') return 'flow';
    const patch: Record<string, string> = {};
    if (dx) {
      if (inline.right && !inline.left) patch.right = round(placedPx(inline.right, computed.right) - dx);
      else patch.left = round(placedPx(inline.left, computed.left) + dx);
    }
    if (dy) {
      if (inline.bottom && !inline.top) patch.bottom = round(placedPx(inline.bottom, computed.bottom) - dy);
      else patch.top = round(placedPx(inline.top, computed.top) + dy);
    }
    edits.push({ target: addressIn(selected.model, element), patch });
  }
  return edits;
}

/** Axes a drag of the selected positioned elements holds still: any of them set from both sides on it. */
export function selectionPinnedAxes(): { x: boolean; y: boolean } {
  const selected = selectedElements();
  const out = { x: false, y: false };
  for (const element of selected?.elements ?? []) {
    if (isElementLocked(element)) continue;
    const pinned = pinnedAxes(styleMap(attributeValue(element, 'style') ?? ''));
    out.x ||= pinned.x;
    out.y ||= pinned.y;
  }
  return out;
}

/** True when every selected element is absolutely positioned. */
export function selectionIsPositioned(): boolean {
  const selected = selectedElements();
  if (!selected) return false;
  const api = boardApi(selected.board);
  return selected.elements.every((element) => {
    const position = styleMap(attributeValue(element, 'style') ?? '').position || api?.inspect(selected.model.tidOf.get(element)!)?.computed.position || '';
    return position === 'absolute' || position === 'fixed';
  });
}

/* -------------------------------- aligning -------------------------------- */

/** True inside a repeated template: its rows follow the data and do not move one by one. */
function inRepeat(element: HtmlElement): boolean {
  for (let up = element.parent; up; up = up.parent) if (up.tag === 'sc-for') return true;
  return false;
}

/** The selected elements as the align row reads them. */
function alignSubjects(selected: ResolvedGroup): AlignSubject[] {
  const api = boardApi(selected.board);
  return selected.elements.map((element) => {
    const inline = styleMap(attributeValue(element, 'style') ?? '');
    const inspection = api?.inspect(selected.model.tidOf.get(element)!) ?? null;
    const computed = inspection?.computed ?? {};
    const translate = inline.translate ?? computed.translate ?? 'none';
    return {
      inline,
      position: inline.position ?? computed.position ?? 'static',
      display: inline.display ?? computed.display ?? 'block',
      parentDisplay: inspection?.parentDisplay ?? 'block',
      translated: translate !== '' && translate !== 'none',
    };
  });
}

/**
 * How the align row works for the selection: `each-other` when several
 * elements are placed with offsets (inline or read `absolute` / `fixed`),
 * so they line up with one another; otherwise each action lines the
 * selection up inside its parent (`parent`, with why it is off).
 */
export function alignMode(blocked: string | null = null): { kind: 'each-other' } | { kind: 'parent'; actions: Record<AlignAction, ParentAlign> } | null {
  const selected = selectedElements();
  if (!selected) return null;
  if (selected.elements.length > 1 && !selected.elements.some(inRepeat) && selectionIsPositioned()) return { kind: 'each-other' };
  return { kind: 'parent', actions: parentAlign(alignSubjects(selected), { readOnly: useDocument.getState().readOnly, blocked }) };
}

/**
 * An align action from the row or its ⌥-letter: several positioned
 * elements line up with each other, anything else inside its parent.
 */
export function runAlign(action: AlignAction): boolean {
  const selected = selectedElements();
  if (!selected || useDocument.getState().readOnly) return false;
  if (selected.elements.length > 1 && !selected.elements.some(inRepeat)) return alignSelection(action);
  const mode = alignMode(selected.elements.some(isElementLocked) ? LOCKED_MESSAGE : null);
  if (mode?.kind !== 'parent') return false;
  const state = mode.actions[action];
  if (state.reason) return false;
  styleSelection(state.patch);
  return true;
}

/**
 * Lines the selected elements up on the box around them all (left to the
 * leftmost edge, centres to its middle...): each moves by its own offset,
 * rounded to 0.1px, as one undo step. Refuses a locked selection, elements
 * not placed with offsets, and elements inside a rotated, flipped or
 * stretched box; announces when nothing needs to move.
 */
export function alignSelection(action: AlignAction): boolean {
  const selected = selectedElements();
  if (!selected || useDocument.getState().readOnly) return false;
  if (selected.elements.some(isElementLocked)) {
    refuseLocked();
    return false;
  }
  if (!selectionIsPositioned()) {
    toast.add({ title: notPositionedMessage('Position', 'Absolute') });
    return false;
  }
  const tids = selected.elements.map((element) => selected.model.tidOf.get(element)!);
  const api = boardApi(selected.board);
  const measured = api?.measure(tids, null);
  if (!measured) return false;
  const boxes = tids.map((tid) => measured.find((box) => box.tid === tid));
  if (boxes.some((box) => !box)) return false;
  if (boxes.some((box) => box!.transformed)) {
    toast.add({ title: TRANSFORMED_MESSAGE });
    return false;
  }
  const offsets = alignOffsets(boxes as AlignBox[], action);
  if (isAligned(offsets)) {
    announce(ALREADY_ALIGNED);
    return false;
  }
  const edits = selected.elements.flatMap((element, index) => {
    const { dx, dy } = offsets[index]!;
    if (!dx && !dy) return [];
    // Every side the element is placed from moves, so it keeps its size: before, only left / top
    // changed, and an element placed from the right (or bottom) stretched to the new edge.
    const inline = styleMap(attributeValue(element, 'style') ?? '');
    const computed = api?.inspect(tids[index]!)?.computed ?? {};
    const patch: Record<string, string> = {};
    // `auto` places from nothing.
    const set = (side: string): boolean => Boolean(inline[side]) && inline[side]!.trim() !== 'auto';
    if (dx) {
      if (set('right')) patch.right = round(placedPx(inline.right, computed.right) - dx);
      if (set('left') || !set('right')) patch.left = round(placedPx(set('left') ? inline.left : undefined, computed.left) + dx);
    }
    if (dy) {
      if (set('bottom')) patch.bottom = round(placedPx(inline.bottom, computed.bottom) - dy);
      if (set('top') || !set('bottom')) patch.top = round(placedPx(set('top') ? inline.top : undefined, computed.top) + dy);
    }
    return [{ target: addressIn(selected.model, element), patch }];
  });
  if (!edits.length || !edit(selected.board, { kind: 'styles', edits })) return false;
  announce(alignInfo(action).done);
  return true;
}

/** Selects the parent element, then the whole artboard. */
export function selectParent(): void {
  const view = useView.getState();
  const { selection } = view;
  if (selection.kind !== 'elements') {
    view.select(NO_SELECTION);
    return;
  }
  const source = useDocument.getState().boards[selection.board]?.source;
  const first = selection.items[0];
  if (!source || !first || first.path.length <= 1) {
    view.select({ kind: 'objects', boards: [selection.board], notes: [] });
    return;
  }
  const model = templateOf(source);
  const element = resolveElement(model, first.tid, first.path);
  const parent = element?.parent;
  if (!parent) {
    view.select({ kind: 'objects', boards: [selection.board], notes: [] });
    return;
  }
  view.select({ kind: 'elements', board: selection.board, items: [{ tid: model.tidOf.get(parent)!, path: first.path.slice(0, -1), instance: first.instance }] });
}

/** Selects the next / previous sibling (Tab / Shift+Tab). */
export function selectSibling(direction: -1 | 1): void {
  const view = useView.getState();
  const { selection } = view;
  if (selection.kind !== 'elements' || !selection.items[0]) return;
  const source = useDocument.getState().boards[selection.board]?.source;
  if (!source) return;
  const model = templateOf(source);
  const first = selection.items[0];
  const element = resolveElement(model, first.tid, first.path);
  if (!element) return;
  const siblings = element.parent ? elementChildren(element.parent) : elementChildren(model.nodes);
  const index = siblings.indexOf(element);
  const next = siblings[(index + direction + siblings.length) % siblings.length]!;
  const item: ElementSelection = { tid: model.tidOf.get(next)!, path: [...first.path.slice(0, -1), siblings.indexOf(next)], instance: 0 };
  view.select({ kind: 'elements', board: selection.board, items: [item] });
}

/** Selects the first child of the selected element (Enter). */
export function selectChild(): void {
  const view = useView.getState();
  const { selection } = view;
  if (selection.kind === 'objects' && selection.boards.length === 1 && selection.notes.length === 0) {
    const source = useDocument.getState().boards[selection.boards[0]!]?.source;
    if (!source) return;
    const model = templateOf(source);
    const first = elementChildren(model.nodes).find((el) => el.tag !== 'helmet');
    if (first) view.select({ kind: 'elements', board: selection.boards[0]!, items: [{ tid: model.tidOf.get(first)!, path: [elementChildren(model.nodes).indexOf(first)], instance: 0 }] });
    return;
  }
  if (selection.kind !== 'elements' || !selection.items[0]) return;
  const source = useDocument.getState().boards[selection.board]?.source;
  if (!source) return;
  const model = templateOf(source);
  const first = selection.items[0];
  const element = resolveElement(model, first.tid, first.path);
  if (!element) return;
  if (isTextEditable(element)) {
    startTextEdit(selection.board, first);
    return;
  }
  const child = elementChildren(element)[0];
  if (child) view.select({ kind: 'elements', board: selection.board, items: [{ tid: model.tidOf.get(child)!, path: [...first.path, 0], instance: first.instance }] });
}

/**
 * Starts in-place text editing of an element: `all` selects its words,
 * `end` puts the caret after them, a point (board pixels) puts it there.
 */
export function startTextEdit(board: string, item: ElementSelection, caret: 'all' | 'end' | { x: number; y: number } = 'all'): boolean {
  // Words typed elsewhere are written first (that may change this board's source).
  const previous = useView.getState().textEdit;
  if (previous) boardApi(previous.board)?.endTextEdit(true);
  const doc = useDocument.getState();
  const source = doc.boards[board]?.source;
  if (!source || doc.readOnly) return false;
  const model = templateOf(source);
  let element = resolveElement(model, item.tid, item.path);
  if (!element && previous?.board === board) {
    // The words just written may have added elements before this one: find it by its place.
    const placed = elementAtPath(model, item.path);
    if (placed) {
      element = placed;
      item = { ...item, tid: model.tidOf.get(placed)! };
    }
  }
  if (!element || !isTextEditable(element)) {
    toast.add({ title: 'This text can’t be edited here', description: 'It mixes words with other layout, or code draws it. Edit the words inside, or ask the agent.' });
    return false;
  }
  const api = boardApi(board);
  if (!api) return false;
  const view = useView.getState();
  view.select({ kind: 'elements', board, items: [item] });
  view.setTextEdit({ board, tid: item.tid });
  if (!api.editText(item.tid, item.instance, textEditOptions(source, model.text, element, view.overrides[board], caret))) {
    view.setTextEdit(null);
    return false;
  }
  return true;
}

/** Moves selected artboards and notes by a world offset (arrow keys); locked ones stay. */
export function nudgeSelection(dx: number, dy: number): void {
  const { selection } = useView.getState();
  if (selection.kind === 'mixed') {
    nudgeMixed(dx, dy);
    return;
  }
  if (selection.kind !== 'objects') return;
  const doc = useDocument.getState();
  const free = unlockedObjects(doc.canvas, selection.boards, selection.notes);
  if (!free.boards.length && !free.notes.length) {
    if (selection.boards.length || selection.notes.length) refuseLocked();
    return;
  }
  doc.updateCanvas((canvas) => moveObjects(canvas, free.boards, free.notes, dx, dy));
}

/**
 * Returns the canvas with artboards and notes moved. Locked ones stay; the
 * same canvas comes back when nothing moved.
 */
export function moveObjects(canvas: Canvas, boards: readonly string[], notes: readonly string[], dx: number, dy: number): Canvas {
  const nextBoards = { ...canvas.boards };
  let moved = false;
  for (const path of boards) {
    const entry = nextBoards[path];
    if (!entry || isLockedObject(entry)) continue;
    nextBoards[path] = { ...entry, x: Math.round(entry.x + dx), y: Math.round(entry.y + dy) };
    moved = true;
  }
  const nextNotes = { ...canvas.notes };
  for (const id of notes) {
    const note = nextNotes[id];
    if (!note || isLockedObject(note)) continue;
    nextNotes[id] = { ...note, x: Math.round(note.x + dx), y: Math.round(note.y + dy) };
    moved = true;
  }
  return moved ? { ...canvas, boards: nextBoards, notes: nextNotes } : canvas;
}

/** What a resize applies to. */
export type ResizeTarget = { board: string } | { note: string };

/**
 * Returns the canvas with an artboard or note given a new world rect
 * (rounded; artboards kept within the size limits, titles take only the width).
 * Locked ones keep their rect.
 */
export function resizeObject(canvas: Canvas, target: ResizeTarget, rect: Rect): Canvas {
  const x = Math.round(rect.x);
  const y = Math.round(rect.y);
  if ('board' in target) {
    const entry = canvas.boards[target.board];
    if (!entry || isLockedObject(entry)) return canvas;
    const size = (v: number) => Math.min(MAX_BOARD_SIZE, Math.max(MIN_BOARD_SIZE, Math.round(v)));
    return { ...canvas, boards: { ...canvas.boards, [target.board]: { ...entry, x, y, w: size(rect.w), h: size(rect.h) } } };
  }
  const note = canvas.notes[target.note];
  if (!note || isLockedObject(note)) return canvas;
  const w = Math.max(16, Math.round(rect.w));
  const patch = note.kind === 'title1' ? { x, y, maxW: w } : { x, y, w, h: Math.max(16, Math.round(rect.h)) };
  return { ...canvas, notes: { ...canvas.notes, [target.note]: { ...note, ...patch } } };
}

export function updateBoard(path: string, patch: Partial<BoardEntry>): void {
  useDocument.getState().updateCanvas((canvas) => {
    const entry = canvas.boards[path];
    if (!entry) return canvas;
    const next: BoardEntry = { ...entry, ...patch };
    for (const [key, value] of Object.entries(patch)) if (value === undefined) delete next[key];
    return { ...canvas, boards: { ...canvas.boards, [path]: next } };
  });
}

/** Moves artboards and notes by a world offset, as one undo step (a finished canvas drag). */
export function commitMove(boards: readonly string[], notes: readonly string[], dx: number, dy: number): void {
  if (!boards.length && !notes.length) return;
  useDocument.getState().updateCanvas((canvas) => moveObjects(canvas, boards, notes, dx, dy));
}

/** Resizes an artboard or note, as one undo step (a finished resize-handle drag). */
export function commitResize(target: ResizeTarget, rect: Rect): void {
  useDocument.getState().updateCanvas((canvas) => resizeObject(canvas, target, rect));
}

