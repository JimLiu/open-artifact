/**
 * Applies an edit to the selected artboard and selects what it created.
 * Locked elements keep their place: an edit that would move, resize, delete
 * or restructure one is refused, and placement is dropped from style edits
 * (both with a toast).
 */
export function edit(board: string, op: BoardOp, options: { selectCreated?: boolean; coalesce?: string } = {}): boolean {
  const outcome = tryEdit(board, op, options);
  if (outcome.trimmed) toast.add({ title: LOCKED_MESSAGE, description: 'Locked elements kept their size and position.' });
  if (outcome.kind === 'locked') refuseLocked();
  if (outcome.kind === 'failed') toast.add({ title: 'That edit does not apply here', description: 'The element is generated by code. Ask the agent to change it.' });
  if (outcome.kind !== 'done') return false;
  if (options.selectCreated && outcome.created.length) {
    useView.getState().select({ kind: 'elements', board, items: outcome.created.map((a) => ({ ...a, instance: 0 })) });
  }
  return true;
}

/** How an edit went: applied (with what it created), refused by a lock, or not applicable. */
export type EditOutcome = ({ kind: 'done'; created: Address[] } | { kind: 'locked' } | { kind: 'failed' }) & { trimmed?: boolean };

/**
 * `edit` without its toasts, for commands that edit several artboards and
 * say once how it went. Locks apply the same way.
 */
export function tryEdit(board: string, op: BoardOp, options: { coalesce?: string; ignoreLocks?: boolean } = {}): EditOutcome {
  let trimmed = false;
  const source = useDocument.getState().boards[board]?.source;
  // `ignoreLocks`: an edit that keeps locked elements where they show (an ungroup writing their places back).
  if (source && !options.ignoreLocks) {
    const verdict = lockVerdict(templateOf(source), op);
    if (verdict.kind === 'refused') return { kind: 'locked' };
    if (verdict.kind === 'trimmed') {
      op = verdict.op;
      trimmed = true;
    }
  }
  // Words being typed on this board are written first: the edit re-renders the board.
  if (useView.getState().textEdit?.board === board) boardApi(board)?.endTextEdit(true);
  const result = useDocument.getState().editBoard(board, op, { coalesce: options.coalesce });
  if (!result) return { kind: 'failed', trimmed };
  return { kind: 'done', created: result.created, trimmed };
}

/** Addresses of the selected elements. */
function selectedAddresses(): { board: string; targets: Address[] } | null {
  const { selection } = useView.getState();
  if (selection.kind !== 'elements' || selection.items.length === 0) return null;
  return { board: selection.board, targets: selection.items.map(({ tid, path }) => ({ tid, path })) };
}

/** Sets inline styles on every selected element. */
export function styleSelection(patch: StylePatch, options: { coalesce?: string } = {}): void {
  const selected = selectedAddresses();
  if (selected) edit(selected.board, { kind: 'style', targets: selected.targets, patch }, options);
}

/** Sets an attribute on the (first) selected element. */
export function attributeSelection(name: string, value: string | null): void {
  const selected = selectedAddresses();
  if (selected) edit(selected.board, { kind: 'attr', target: selected.targets[0]!, name, value });
}

/* ------------------------------ selection ------------------------------- */

/** Deletes whatever is selected. */
export function deleteSelection(): void {
  if (refuseWhileCropping()) return;
  const view = useView.getState();
  const doc = useDocument.getState();
  const { selection } = view;
  if (selection.kind === 'mixed') {
    deleteMixed(selection);
    return;
  }
  if (selection.kind === 'elements') {
    if (edit(selection.board, { kind: 'remove', targets: selection.items.map(({ tid, path }) => ({ tid, path })) })) {
      view.select(NO_SELECTION);
      announce(selection.items.length === 1 ? 'Deleted' : `Deleted ${selection.items.length} elements`);
    }
  } else if (selection.kind === 'objects') {
    // Locked artboards and notes stay; only an all-locked selection is refused.
    const free = unlockedObjects(doc.canvas, selection.boards, selection.notes);
    if (!free.boards.length && !free.notes.length) {
      if (anyLockedObject(doc.canvas, selection.boards, selection.notes)) refuseLocked();
      return;
    }
    if (free.notes.length) {
      doc.updateCanvas((canvas) => {
        const notes = { ...canvas.notes };
        for (const id of free.notes) delete notes[id];
        return { ...canvas, notes };
      });
    }
    if (free.boards.length) doc.deleteBoards(free.boards);
    const kept = selection.boards.length + selection.notes.length - free.boards.length - free.notes.length;
    view.select(kept ? { kind: 'objects', boards: selection.boards.filter((path) => !free.boards.includes(path)), notes: selection.notes.filter((id) => !free.notes.includes(id)) } : NO_SELECTION);
    const count = free.notes.length + free.boards.length;
    announce(count === 1 ? 'Deleted' : `Deleted ${count} items`);
  }
}

/** Duplicates the selection next to itself. */
export function duplicateSelection(): void {
  if (refuseWhileCropping()) return;
  const view = useView.getState();
  const doc = useDocument.getState();
  const { selection } = view;
  if (selection.kind === 'elements') {
    edit(selection.board, { kind: 'duplicate', targets: selection.items.map(({ tid, path }) => ({ tid, path })) }, { selectCreated: true });
    return;
  }
  if (selection.kind === 'mixed') {
    duplicateMixed(selection);
    return;
  }
  if (selection.kind !== 'objects') return;
  view.select(duplicateObjects(doc, selection.boards, selection.notes));
}

/**
 * Copies artboards and notes next to themselves, or `by` an offset; returns
 * the copies. Locked ones copy too; the copies start unlocked.
 */
function duplicateObjects(doc: ReturnType<typeof useDocument.getState>, boards: readonly string[], notes: readonly string[], by?: { dx: number; dy: number }): { kind: 'objects'; boards: string[]; notes: string[] } {
  const selection = { boards, notes };
  const taken = new Set([...Object.keys(doc.boards), ...Object.keys(doc.canvas.boards)]);
  const newBoards: string[] = [];
  for (const path of selection.boards) {
    const entry = doc.canvas.boards[path];
    const source = doc.boards[path]?.source;
    if (!entry || !source) continue;
    const name = freeBoardName(path.replace(/\.dc\.html$/, '').replace(/^.*\//, ''), taken);
    taken.add(name);
    const at = by ? { x: Math.round(entry.x + by.dx), y: Math.round(entry.y + by.dy) } : { x: entry.x + entry.w + 80 };
    useDocument.getState().createBoard(name, source, { ...withoutLock(entry), ...at });
    newBoards.push(name);
  }
  let newNotes: string[] = [];
  if (selection.notes.length) {
    useDocument.getState().updateCanvas((canvas) => {
      // Copies of a group form a new group of their own; copies start unlocked.
      const sources = selection.notes.flatMap((id) => (canvas.notes[id] ? [canvas.notes[id]!] : []));
      const copied = addNoteCopies(canvas, sources, (note) => ({ ...withoutLock(note), ...(by ? { x: Math.round(note.x + by.dx), y: Math.round(note.y + by.dy) } : { x: note.x + 24, y: note.y + 24 }) }));
      newNotes = copied.ids;
      return copied.canvas;
    });
  }
  return { kind: 'objects', boards: newBoards, notes: newNotes };
}

/* ------------------------- across several files ------------------------- */

const addresses = (group: BoardElements): Address[] => group.items.map(({ tid, path }) => ({ tid, path }));

/**
 * Deletes a mixed selection as one undo step: each artboard removes its
 * own elements, artboards and notes go as canvas objects. Locked members
 * stay selected; an all-locked selection is refused.
 */
function deleteMixed(selection: MixedSelection): void {
  const doc = useDocument.getState();
  if (doc.readOnly) return;
  const { elements: groups, ...free } = unlockedMixed(selection);
  if (!groups.length && !free.boards.length && !free.notes.length) {
    refuseLocked();
    return;
  }
  const removed: string[] = [];
  doc.transact(() => {
    for (const group of groups) if (edit(group.board, { kind: 'remove', targets: addresses(group) })) removed.push(group.board);
    removeObjects(free.boards, free.notes);
  });
  const gone = groups.filter((group) => removed.includes(group.board));
  const count = gone.reduce((sum, group) => sum + group.items.length, 0) + free.boards.length + free.notes.length;
  if (!count) return;
  // What stays (locked, or on an artboard that refused) stays selected.
  const left = selection.elements.map((group) => {
    const done = gone.find((entry) => entry.board === group.board);
    return done ? { board: group.board, items: group.items.filter((item) => !done.items.includes(item)) } : group;
  });
  useView.getState().select(
    selectionFrom({
      boards: selection.boards.filter((path) => !free.boards.includes(path)),
      notes: selection.notes.filter((id) => !free.notes.includes(id)),
      elements: left,
    }),
  );
  announce(count === 1 ? 'Deleted' : `Deleted ${count} items`);
}

/** The members of a mixed selection that are not locked themselves: what a delete or a cut removes. */
export function unlockedMixed(selection: MixedSelection): { boards: string[]; notes: string[]; elements: BoardElements[] } {
  const free = unlockedObjects(useDocument.getState().canvas, selection.boards, selection.notes);
  return { boards: [...free.boards], notes: [...free.notes], elements: unlockedElementGroups(selection) };
}

/**
 * Removes the elements of a mixed selection as one undo step, for a cut:
 * its artboards and notes stay, and stay selected. False when nothing went.
 */
export function removeMixedElements(selection: MixedSelection): boolean {
  const doc = useDocument.getState();
  if (doc.readOnly) return false;
  let removed = false;
  doc.transact(() => {
    for (const group of selection.elements) if (edit(group.board, { kind: 'remove', targets: addresses(group) })) removed = true;
  });
  if (removed) useView.getState().select(selectionFrom({ boards: selection.boards, notes: selection.notes, elements: [] }));
  return removed;
}

/** True when one of these elements is locked (it keeps its place and size). */
export function anyElementLocked(groups: readonly BoardElements[]): boolean {
  return resolvedGroups(groups).some((group) => group.elements.some(isElementLocked));
}

/** Each selected element's rendered value of one property, across artboards (a merged row). */
export function mixedComputed(groups: readonly BoardElements[], property: string): string[] {
  return resolvedGroups(groups).flatMap((group) => {
    const api = boardApi(group.board);
    return group.elements.map((element) => api?.inspect(group.model.tidOf.get(element)!)?.computed[property] ?? '');
  });
}

/**
 * One style patch on every selected element across artboards, as one
 * undo step; false when nothing took it.
 */
export function styleMixed(groups: readonly BoardElements[], patch: StylePatch): boolean {
  const doc = useDocument.getState();
  if (doc.readOnly) return false;
  let styled = false;
  doc.transact(() => {
    for (const group of resolvedGroups(groups)) {
      const edits = group.elements.map((element) => ({ target: addressIn(group.model, element), patch }));
      if (tryEdit(group.board, { kind: 'styles', edits }).kind === 'done') styled = true;
    }
  });
  return styled;
}

/** Removes artboards and notes from the canvas. */
function removeObjects(boards: readonly string[], notes: readonly string[]): void {
  const doc = useDocument.getState();
  if (notes.length) {
    doc.updateCanvas((canvas) => {
      const next = { ...canvas.notes };
      for (const id of notes) delete next[id];
      return { ...canvas, notes: next };
    });
  }
  if (boards.length) doc.deleteBoards(boards);
}

/** Toast when no artboard of a mixed selection could duplicate its elements. */
export const NOTHING_DUPLICATED = 'Nothing duplicated — an artboard could not apply the duplicate.';
/** Toast when some artboards could and one could not. */
export const PARTLY_DUPLICATED = 'Duplicated — one artboard’s duplicate failed';

/**
 * Duplicates a mixed selection as one undo step: each artboard copies its
 * own elements, artboards and notes are copied as canvas objects. The
 * copies are selected.
 */
function duplicateMixed(selection: MixedSelection): void {
  const doc = useDocument.getState();
  if (doc.readOnly) return;
  const created: BoardElements[] = [];
  let failed = 0;
  let copies = { boards: [] as string[], notes: [] as string[] };
  doc.transact(() => {
    for (const group of selection.elements) {
      const outcome = tryEdit(group.board, { kind: 'duplicate', targets: addresses(group) });
      if (outcome.kind === 'done') created.push({ board: group.board, items: outcome.created.map((address) => ({ ...address, instance: 0 })) });
      else failed += 1;
    }
    copies = duplicateObjects(useDocument.getState(), selection.boards, selection.notes);
  });
  if (failed && !created.length && !copies.boards.length && !copies.notes.length) {
    toast.add({ title: NOTHING_DUPLICATED });
    return;
  }
  if (failed) toast.add({ title: PARTLY_DUPLICATED });
  useView.getState().select(selectionFrom({ ...copies, elements: created }));
  announce('Duplicated');
}

