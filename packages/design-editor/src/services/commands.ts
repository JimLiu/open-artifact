/**
 * Moves a page to follow `afterId` (`null` = first) in one undo step. The
 * current page stays current. Returns whether the order changed.
 */
export function movePage(id: string, afterId: string | null): boolean {
  const doc = useDocument.getState();
  if (doc.readOnly) return false;
  const before = doc.canvas;
  doc.updateCanvas((canvas) => moveCanvasPage(canvas, id, afterId));
  return useDocument.getState().canvas !== before;
}

/** Moves a page one place up or down the list and says so. */
export function stepPage(id: string, direction: -1 | 1): boolean {
  const pages = useDocument.getState().canvas.pages;
  const at = pages.findIndex((p) => p.id === id);
  const to = at + direction;
  if (at < 0 || to < 0 || to >= pages.length) return false;
  // Moving up lands after the page two places up; moving down, after the next one.
  const after = direction < 0 ? (to === 0 ? null : pages[to - 1]!.id) : pages[to]!.id;
  const moved = movePage(id, after);
  if (moved) announce(direction < 0 ? 'Page moved up' : 'Page moved down');
  return moved;
}

/** Deletes a page with its artboards and notes (undoable). */
export function deletePage(id: string): void {
  const doc = useDocument.getState();
  const { canvas } = doc;
  if (canvas.pages.length <= 1) return;
  const first = canvas.pages[0]!.id;
  const onPage = (item: { page?: string }) => (item.page ?? first) === id;
  const boards = Object.entries(canvas.boards).filter(([, e]) => onPage(e)).map(([p]) => p);
  doc.updateCanvas((c) => {
    const notes = Object.fromEntries(Object.entries(c.notes).filter(([, n]) => !onPage(n)));
    const pages = c.pages.filter((p) => p.id !== id);
    // Items on the old first page move to the new first page implicitly.
    return { ...c, pages, notes };
  });
  if (boards.length) doc.deleteBoards(boards);
  useView.getState().setPage(useDocument.getState().canvas.pages[0]?.id ?? null);
}

/* -------------------------------- history ------------------------------- */

/**
 * Lets go of what an undo or redo took away: artboards and notes no longer
 * on the canvas, and elements no longer in their artboard's source (an
 * undone draw or paste). An artboard whose source has not loaded keeps its
 * elements.
 */
export function dropVanishedSelection(): void {
  const view = useView.getState();
  const { canvas, boards: sources } = useDocument.getState();
  const parts = selectionParts(view.selection);
  const boards = parts.boards.filter((path) => canvas.boards[path]);
  const notes = parts.notes.filter((id) => canvas.notes[id]);
  let dropped = boards.length !== parts.boards.length || notes.length !== parts.notes.length;
  const elements = parts.elements.map((group) => {
    if (!canvas.boards[group.board]) {
      dropped = true;
      return { board: group.board, items: [] };
    }
    const source = sources[group.board]?.source;
    if (source == null) return group;
    const model = templateOf(source);
    const items = group.items.filter((item) => resolveElement(model, item.tid, item.path));
    if (items.length !== group.items.length) dropped = true;
    return { board: group.board, items };
  });
  if (dropped) view.select(selectionFrom({ boards, notes, elements, primary: parts.primary }));
}

export function undo(): void {
  const entry = useDocument.getState().undoLast();
  if (entry) {
    useView.getState().tick();
    dropVanishedSelection();
  }
  announce(entry ? (entry.scope === 'canvas' && entry.label ? `${entry.label} undone.` : 'Undo') : 'Nothing to undo');
}

export function redo(): void {
  const entry = useDocument.getState().redoLast();
  if (entry) {
    useView.getState().tick();
    dropVanishedSelection();
  }
  announce(entry ? (entry.scope === 'canvas' && entry.label ? `${entry.label} redone.` : 'Redo') : 'Nothing to redo');
}

/* --------------------------------- flip --------------------------------- */

/** Why an element cannot be flipped on an axis, or `null`. */
function flipRefusal(element: HtmlElement, computed: Record<string, string> | undefined, axis: 'x' | 'y'): string | null {
  if (element.tag === 'dc-import' || element.tag === 'x-import') return 'Component instances can’t be flipped.';
  if (element.tag === 'sc-for' || element.tag === 'sc-if' || element.tag === 'helmet') return 'Repeats and conditions can’t be flipped.';
  if (hasDynamicStyle(element)) return 'Its style comes from the page’s script.';
  if (!computed) return 'It isn’t shown right now.';
  if (computed.display === 'inline') return 'Inline elements can’t be flipped.';
  for (const name of ['rotate', 'scale', 'translate'] as const) if (computed[name] && computed[name] !== 'none') return 'Its transform is set in code.';
  const inline = styleMap(attributeValue(element, 'style') ?? '');
  if (!inline.transform && computed.transform && computed.transform !== 'none') return 'Its transform is set in code.';
  if (parseFloat(computed[axis === 'x' ? 'width' : 'height'] ?? '0') === 0) return 'It has no size on that axis.';
  return null;
}

/** Mirrors the selected elements horizontally (⇧H) or vertically (⇧V). */
export function flipSelection(axis: 'x' | 'y'): void {
  const doc = useDocument.getState();
  if (doc.readOnly) return;
  if (refuseWhileCropping(CROP_MESSAGES.flip)) return;
  const { selection } = useView.getState();
  if (selection.kind === 'mixed') {
    // Each artboard flips its own elements; artboards and notes do not flip.
    const plans = resolvedGroups(selection.elements).map((group) => ({ board: group.board, ...flipEdits(group, axis) }));
    const reasons = plans.flatMap((plan) => plan.reasons);
    if (!plans.some((plan) => plan.edits.length)) {
      toast.add({ title: 'Couldn’t flip', description: reasons[0] });
      return;
    }
    let flipped = false;
    doc.transact(() => {
      for (const plan of plans) if (plan.edits.length && tryEdit(plan.board, { kind: 'styles', edits: plan.edits }).kind === 'done') flipped = true;
    });
    if (flipped && reasons.length) toast.add({ title: 'Some elements couldn’t be flipped', description: `${reasons[0]} The rest flipped.` });
    return;
  }
  const selected = selectedElements();
  if (!selected) return;
  const { edits, reasons } = flipEdits(selected, axis);
  if (!edits.length) {
    toast.add({ title: 'Couldn’t flip', description: reasons[0] });
    return;
  }
  if (edit(selected.board, { kind: 'styles', edits }) && reasons.length) toast.add({ title: 'Some elements couldn’t be flipped', description: `${reasons[0]} The rest flipped.` });
}

/** The style edits that flip one artboard's selected elements, and why some could not. */
function flipEdits(selected: ResolvedGroup, axis: 'x' | 'y'): { edits: { target: Address; patch: StylePatch }[]; reasons: string[] } {
  const { model, board } = selected;
  const api = boardApi(board);
  // Shapes flip with their drawing.
  const targets = new Set<HtmlElement>();
  for (const element of selected.elements) {
    let target = element;
    for (let up = element.parent; up; up = up.parent) if (up.tag === 'svg') target = up;
    targets.add(target);
  }
  const edits: { target: Address; patch: StylePatch }[] = [];
  const reasons: string[] = [];
  for (const element of targets) {
    const computed = api?.inspect(model.tidOf.get(element)!)?.computed;
    let reason = flipRefusal(element, computed, axis);
    if (!reason) {
      const next = flipTransform(styleMap(attributeValue(element, 'style') ?? '').transform ?? '', axis);
      if (next === null) reason = 'Its transform is too complex to flip.';
      else edits.push({ target: addressIn(model, element), patch: { transform: next || null } });
    }
    if (reason) reasons.push(reason);
  }
  return { edits, reasons };
}

