/** Inline style copied with ⌥⌘C. */
let copiedStyle: string | null = null;

/** Copies the inline style of the (first) selected element. */
export function copyProperties(): void {
  const selected = selectedElements();
  if (!selected) return;
  if (!hasPropertiesToCopy()) {
    toast.add({ title: `${NO_PROPERTIES}.` });
    return;
  }
  copiedStyle = attributeValue(selected.elements[0]!, 'style') ?? '';
  toast.add({ title: 'Properties copied' });
}

/** Why Copy properties does nothing: the element has no inline style. */
export const NO_PROPERTIES = 'This element has no properties to copy';

/** Whether the (first) selected element has an inline style to copy. */
export function hasPropertiesToCopy(): boolean {
  const selected = selectedElements();
  return Boolean(selected && (attributeValue(selected.elements[0]!, 'style') ?? '').trim());
}

/** Replaces the inline style of every selected element with the copied one. */
export function pasteProperties(): void {
  const selected = selectedElements();
  if (!selected || copiedStyle === null) return;
  const copied = styleMap(copiedStyle);
  const edits = selected.elements.map((element) => {
    const patch: Record<string, string | null> = { ...copied };
    for (const property of Object.keys(styleMap(attributeValue(element, 'style') ?? ''))) if (!(property in copied)) patch[property] = null;
    return { target: addressIn(selected.model, element), patch };
  });
  edit(selected.board, { kind: 'styles', edits });
}

/** True once properties were copied. */
export function hasCopiedProperties(): boolean {
  return copiedStyle !== null;
}

/* -------------------------------- moving -------------------------------- */

const px = (value: string | undefined): number => {
  const number = parseFloat(value ?? '');
  return Number.isFinite(number) ? number : 0;
};
const round = (value: number): string => `${Math.round(value * 100) / 100}px`;

/**
 * Moves absolutely positioned elements by an offset in artboard pixels,
 * through `left`/`top` (or `right`/`bottom` when only those are set).
 * Locked elements stay (with a toast when all of them are locked).
 * Returns `false` when any selected element is in the flow.
 */
export function moveSelectedElements(dx: number, dy: number, options: { coalesce?: string } = {}): boolean {
  const selected = selectedElements();
  if (!selected) return false;
  const free = selected.elements.filter((element) => !isElementLocked(element));
  if (!free.length) {
    refuseLocked();
    return false;
  }
  const api = boardApi(selected.board);
  const edits: { target: Address; patch: StylePatch }[] = [];
  for (const element of free) {
    const inline = styleMap(attributeValue(element, 'style') ?? '');
    const tid = selected.model.tidOf.get(element)!;
    const computed = api?.inspect(tid)?.computed ?? {};
    const position = inline.position || computed.position || '';
    if (position !== 'absolute' && position !== 'fixed') return false;
    const patch: Record<string, string> = {};
    if (dx) {
      if (inline.right && !inline.left) patch.right = round(px(inline.right) - dx);
      else patch.left = round(px(inline.left || computed.left) + dx);
    }
    if (dy) {
      if (inline.bottom && !inline.top) patch.bottom = round(px(inline.bottom) - dy);
      else patch.top = round(px(inline.top || computed.top) + dy);
    }
    edits.push({ target: addressIn(selected.model, element), patch });
  }
  if (!edits.length) return false;
  return edit(selected.board, { kind: 'styles', edits }, { coalesce: options.coalesce });
}

/** Axes a drag of the selected positioned elements holds still: any of them set from both sides on it. */
export function selectionPinnedAxes(): { x: boolean; y: boolean } {
  const selected = selectedElements();
  const out = { x: false, y: false };
  for (const element of selected?.elements ?? []) {
    if (isElementLocked(element)) continue;
    const pinned = pinnedAxes(styleMap(attributeValue(element, 'style') ?? ''));
    out.x ||= pinned.x;
    out.y ||= pinned.y;
  }
  return out;
}

/** True when every selected element is absolutely positioned. */
export function selectionIsPositioned(): boolean {
  const selected = selectedElements();
  if (!selected) return false;
  const api = boardApi(selected.board);
  return selected.elements.every((element) => {
    const position = styleMap(attributeValue(element, 'style') ?? '').position || api?.inspect(selected.model.tidOf.get(element)!)?.computed.position || '';
    return position === 'absolute' || position === 'fixed';
  });
}

/** Selects the parent element, then the whole artboard. */
export function selectParent(): void {
  const view = useView.getState();
  const { selection } = view;
  if (selection.kind !== 'elements') {
    view.select(NO_SELECTION);
    return;
  }
  const source = useDocument.getState().boards[selection.board]?.source;
  const first = selection.items[0];
  if (!source || !first || first.path.length <= 1) {
    view.select({ kind: 'objects', boards: [selection.board], notes: [] });
    return;
  }
  const model = templateOf(source);
  const element = resolveElement(model, first.tid, first.path);
  const parent = element?.parent;
  if (!parent) {
    view.select({ kind: 'objects', boards: [selection.board], notes: [] });
    return;
  }
  view.select({ kind: 'elements', board: selection.board, items: [{ tid: model.tidOf.get(parent)!, path: first.path.slice(0, -1), instance: first.instance }] });
}

/** Selects the next / previous sibling (Tab / Shift+Tab). */
export function selectSibling(direction: -1 | 1): void {
  const view = useView.getState();
  const { selection } = view;
  if (selection.kind !== 'elements' || !selection.items[0]) return;
  const source = useDocument.getState().boards[selection.board]?.source;
  if (!source) return;
  const model = templateOf(source);
  const first = selection.items[0];
  const element = resolveElement(model, first.tid, first.path);
  if (!element) return;
  const siblings = element.parent ? elementChildren(element.parent) : elementChildren(model.nodes);
  const index = siblings.indexOf(element);
  const next = siblings[(index + direction + siblings.length) % siblings.length]!;
  const item: ElementSelection = { tid: model.tidOf.get(next)!, path: [...first.path.slice(0, -1), siblings.indexOf(next)], instance: 0 };
  view.select({ kind: 'elements', board: selection.board, items: [item] });
}

/** Selects the first child of the selected element (Enter). */
export function selectChild(): void {
  const view = useView.getState();
  const { selection } = view;
  if (selection.kind === 'objects' && selection.boards.length === 1 && selection.notes.length === 0) {
    const source = useDocument.getState().boards[selection.boards[0]!]?.source;
    if (!source) return;
    const model = templateOf(source);
    const first = elementChildren(model.nodes).find((el) => el.tag !== 'helmet');
    if (first) view.select({ kind: 'elements', board: selection.boards[0]!, items: [{ tid: model.tidOf.get(first)!, path: [elementChildren(model.nodes).indexOf(first)], instance: 0 }] });
    return;
  }
  if (selection.kind !== 'elements' || !selection.items[0]) return;
  const source = useDocument.getState().boards[selection.board]?.source;
  if (!source) return;
  const model = templateOf(source);
  const first = selection.items[0];
  const element = resolveElement(model, first.tid, first.path);
  if (!element) return;
  if (isTextEditable(element)) {
    startTextEdit(selection.board, first);
    return;
  }
  const child = elementChildren(element)[0];
  if (child) view.select({ kind: 'elements', board: selection.board, items: [{ tid: model.tidOf.get(child)!, path: [...first.path, 0], instance: first.instance }] });
}

/**
 * Starts in-place text editing of an element: `all` selects its words,
 * `end` puts the caret after them, a point (board pixels) puts it there.
 */
export function startTextEdit(board: string, item: ElementSelection, caret: 'all' | 'end' | { x: number; y: number } = 'all'): boolean {
  // Words typed elsewhere are written first (that may change this board's source).
  const previous = useView.getState().textEdit;
  if (previous) boardApi(previous.board)?.endTextEdit(true);
  const doc = useDocument.getState();
  const source = doc.boards[board]?.source;
  if (!source || doc.readOnly) return false;
  const model = templateOf(source);
  let element = resolveElement(model, item.tid, item.path);
  if (!element && previous?.board === board) {
    // The words just written may have added elements before this one: find it by its place.
    const placed = elementAtPath(model, item.path);
    if (placed) {
      element = placed;
      item = { ...item, tid: model.tidOf.get(placed)! };
    }
  }
  if (!element || !isTextEditable(element)) {
    toast.add({ title: 'This text can’t be edited here', description: 'It mixes words with other layout, or code draws it. Edit the words inside, or ask the agent.' });
    return false;
  }
  const api = boardApi(board);
  if (!api) return false;
  const view = useView.getState();
  view.select({ kind: 'elements', board, items: [item] });
  view.setTextEdit({ board, tid: item.tid });
  if (!api.editText(item.tid, item.instance, textEditOptions(source, model.text, element, view.overrides[board], caret))) {
    view.setTextEdit(null);
    return false;
  }
  return true;
}

/** Moves selected artboards and notes by a world offset (arrow keys); locked ones stay. */
export function nudgeSelection(dx: number, dy: number): void {
  const { selection } = useView.getState();
  if (selection.kind !== 'objects') return;
  const doc = useDocument.getState();
  const free = unlockedObjects(doc.canvas, selection.boards, selection.notes);
  if (!free.boards.length && !free.notes.length) {
    if (selection.boards.length || selection.notes.length) refuseLocked();
    return;
  }
  doc.updateCanvas((canvas) => moveObjects(canvas, free.boards, free.notes, dx, dy));
}

/**
 * Returns the canvas with artboards and notes moved. Locked ones stay; the
 * same canvas comes back when nothing moved.
 */
export function moveObjects(canvas: Canvas, boards: readonly string[], notes: readonly string[], dx: number, dy: number): Canvas {
  const nextBoards = { ...canvas.boards };
  let moved = false;
  for (const path of boards) {
    const entry = nextBoards[path];
    if (!entry || isLockedObject(entry)) continue;
    nextBoards[path] = { ...entry, x: Math.round(entry.x + dx), y: Math.round(entry.y + dy) };
    moved = true;
  }
  const nextNotes = { ...canvas.notes };
  for (const id of notes) {
    const note = nextNotes[id];
    if (!note || isLockedObject(note)) continue;
    nextNotes[id] = { ...note, x: Math.round(note.x + dx), y: Math.round(note.y + dy) };
    moved = true;
  }
  return moved ? { ...canvas, boards: nextBoards, notes: nextNotes } : canvas;
}

/** What a resize applies to. */
export type ResizeTarget = { board: string } | { note: string };

/**
 * Returns the canvas with an artboard or note given a new world rect
 * (rounded; artboards kept within the size limits, titles take only the width).
 * Locked ones keep their rect.
 */
export function resizeObject(canvas: Canvas, target: ResizeTarget, rect: Rect): Canvas {
  const x = Math.round(rect.x);
  const y = Math.round(rect.y);
  if ('board' in target) {
    const entry = canvas.boards[target.board];
    if (!entry || isLockedObject(entry)) return canvas;
    const size = (v: number) => Math.min(MAX_BOARD_SIZE, Math.max(MIN_BOARD_SIZE, Math.round(v)));
    return { ...canvas, boards: { ...canvas.boards, [target.board]: { ...entry, x, y, w: size(rect.w), h: size(rect.h) } } };
  }
  const note = canvas.notes[target.note];
  if (!note || isLockedObject(note)) return canvas;
  const w = Math.max(16, Math.round(rect.w));
  const patch = note.kind === 'title1' ? { x, y, maxW: w } : { x, y, w, h: Math.max(16, Math.round(rect.h)) };
  return { ...canvas, notes: { ...canvas.notes, [target.note]: { ...note, ...patch } } };
}

/** Moves artboards and notes by a world offset, as one undo step (a finished canvas drag). */
export function commitMove(boards: readonly string[], notes: readonly string[], dx: number, dy: number): void {
  if (!boards.length && !notes.length) return;
  useDocument.getState().updateCanvas((canvas) => moveObjects(canvas, boards, notes, dx, dy));
}

/** Resizes an artboard or note, as one undo step (a finished resize-handle drag). */
export function commitResize(target: ResizeTarget, rect: Rect): void {
  useDocument.getState().updateCanvas((canvas) => resizeObject(canvas, target, rect));
}

