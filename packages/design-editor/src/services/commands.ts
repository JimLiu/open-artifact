/** Replaces the selected component instances with copies of their components. */
export async function detachSelection(): Promise<void> {
  const doc = useDocument.getState();
  if (doc.readOnly) return;
  const selected = selectedElements();
  const refusal = detachSelectionRefusal();
  if (!selected || refusal) {
    toast.add({ title: 'Couldn’t detach', description: refusal ?? undefined });
    return;
  }
  const { board } = selected;
  const api = boardApi(board);
  const dir = board.includes('/') ? board.slice(0, board.lastIndexOf('/') + 1) : '';
  // Resolve everything first, then edit last-to-first so earlier addresses stay valid.
  const plans: { target: Address; html: string; helmet: string }[] = [];
  const failures: string[] = [];
  for (const element of selected.elements) {
    const name = attributeValue(element, 'name') ?? '';
    const props = instanceProps(element);
    if (!props.ok) {
      failures.push(props.reason);
      continue;
    }
    let source: string;
    try {
      source = await loadBoardSource(`${dir}${name}.dc.html`);
    } catch {
      failures.push(`The component “${name}” could not be loaded.`);
      continue;
    }
    const defaults = defaultProps(parseDcDocument(source).props);
    const values = api?.importValues(name, props.props) ?? { ...defaults, ...props.props };
    const result = detachMarkup(source, element, values);
    if (!result.ok) {
      failures.push(result.reason);
      continue;
    }
    // The copy starts unlocked, whatever the component locks.
    plans.push({ target: addressIn(selected.model, element), html: withoutLocks(result.html), helmet: result.helmet });
  }
  if (!plans.length) {
    toast.add({ title: 'Couldn’t detach', description: failures[0] });
    return;
  }
  const current = useDocument.getState().boards[board]?.source ?? '';
  const helmet = [...new Set(plans.map((plan) => plan.helmet).filter((text) => text && !current.includes(text)))].join('\n');
  edit(board, { kind: 'replace', edits: plans.map(({ target, html }) => ({ target, html })), helmet: helmet || undefined }, { selectCreated: true });
  if (failures.length) toast.add({ title: `${plans.length} of ${plans.length + failures.length} instances were detached.`, description: failures[0] });
}

/** True when an element has words of its own between its tags. */
function hasOwnWords(element: HtmlElement): boolean {
  return element.children.some((child) => child.type === 'text' && child.value.trim() !== '');
}

/** True when the template writes words anywhere inside an element. */
function writesWords(element: HtmlElement): boolean {
  return element.children.some((child) => (child.type === 'text' && child.value.trim() !== '') || (child.type === 'element' && writesWords(child)));
}

/**
 * A double-click asked to edit the words of an element that is not one
 * block of text.
 * `point` is where, in board pixels. A component instance edits the words
 * under the point where it draws them; an element mixing loose words with
 * other layout has each run wrapped in a `<span>`, then the run under the
 * point is edited; anything else says why it can't be.
 */
export function editTextAt(board: string, item: ElementSelection, point: { x: number; y: number }): void {
  const doc = useDocument.getState();
  const source = doc.boards[board]?.source;
  const api = boardApi(board);
  if (!source || doc.readOnly || !api) return;
  const element = resolveElement(templateOf(source), item.tid, item.path);
  if (!element) return;
  const view = useView.getState();
  if (element.tag === 'x-import') {
    const previous = view.textEdit;
    if (previous) boardApi(previous.board)?.endTextEdit(true);
    const targets = importTargets(source, element, view.overrides[board]);
    view.select({ kind: 'elements', board, items: [item] });
    view.setTextEdit({ board, tid: item.tid, plain: true });
    if (targets.length && api.editImportText(item.tid, item.instance, point.x, point.y, targets)) return;
    useView.getState().setTextEdit(null);
    const from = instanceWordsSource(element, api.wordsAt(item.tid, item.instance, point.x, point.y));
    if (!from) {
      toast.add({ title: 'Ask the agent to edit this code component.' });
      return;
    }
    // One toast per instance and reason, however often it is double-clicked.
    toast.add({
      id: `instance-words-${board}-${item.tid}-${from.kind}`,
      title: instanceWordsMessage(from),
      ...(from.kind === 'prop'
        ? {
            actionProps: {
              children: `Show ${from.component} props`,
              onClick: () => {
                useView.getState().select({ kind: 'elements', board, items: [item] });
                useView.getState().setPanel('code', true);
              },
            },
          }
        : {}),
    });
    return;
  }
  if (!hasOwnWords(element)) {
    const drawn = !writesWords(element) && (api.inspect(item.tid)?.text ?? '').trim() !== '';
    toast.add(
      drawn
        ? { title: 'Ask the agent to edit this code-drawn text.' }
        : { title: 'This text can’t be edited here', description: 'It mixes words with other layout, or code draws it. Edit the words inside, or ask the agent.' },
    );
    return;
  }
  const display = api.inspect(item.tid)?.computed.display ?? '';
  const result = doc.editBoard(board, { kind: 'wrapText', target: { tid: item.tid, path: item.path }, inline: !/flex|grid/.test(display) });
  if (!result || !result.created.length) {
    toast.add({ title: 'This element mixes text with other layout, so it can’t be edited inline as one block.' });
    return;
  }
  const spans = result.created.map((address) => ({ ...address, instance: item.instance }));
  view.select({ kind: 'elements', board, items: spans });
  // Once the board shows the spans, edit the one under the point.
  setTimeout(() => {
    const current = boardApi(board);
    if (!current || useView.getState().textEdit) return;
    const rects = current.rects(spans.map((span) => span.tid));
    const under = spans.find((span) => {
      const rect = rects[span.tid]?.[span.instance];
      return rect && point.x >= rect.x && point.x <= rect.x + rect.width && point.y >= rect.y && point.y <= rect.y + rect.height;
    });
    const span = under ?? (spans.length === 1 ? spans[0] : undefined);
    if (span) startTextEdit(board, span, under ? point : 'all');
  }, 350);
}
