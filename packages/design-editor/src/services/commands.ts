/** Adds a blank artboard; placed at `at` or after the current page's rows. */
export function addBoard(at?: { x: number; y: number }, size = { w: 1280, h: 800 }): string | null {
  const doc = useDocument.getState();
  if (doc.readOnly) return null;
  const view = useView.getState();
  const taken = new Set([...Object.keys(doc.boards), ...Object.keys(doc.canvas.boards)]);
  const path = freeBoardName('Artboard', taken);
  const position = at ?? placeNewBoard(doc.canvas, view.page, size);
  const entry: BoardEntry = { x: Math.round(position.x), y: Math.round(position.y), w: size.w, h: size.h, title: path.replace(/\.dc\.html$/, '').replace(/-/g, ' ') };
  if (view.page && doc.canvas.pages.length > 1 && view.page !== doc.canvas.pages[0]?.id) entry.page = view.page;
  doc.createBoard(path, newBoardSource({ title: entry.title!, width: size.w, height: size.h }), entry);
  view.select({ kind: 'objects', boards: [path], notes: [] });
  if (!at) zoomToBoards([path]);
  return path;
}

/**
 * The Artboard tool picked with Enter: an artboard goes in the next free
 * spot at once, and its name field in the properties panel takes focus.
 */
export function addBoardFromKeyboard(): string | null {
  const path = addBoard();
  if (!path) return null;
  const view = useView.getState();
  view.setTool('select');
  view.setPanel('properties', true);
  view.requestFocus(`board-name:${path}`);
  announce('Artboard added');
  return path;
}

/** Adds a note at a world point and selects it. */
export function addNote(kind: CanvasNote['kind'] | undefined, at: { x: number; y: number }, extra: Partial<CanvasNote> = {}): string | null {
  const doc = useDocument.getState();
  if (doc.readOnly) return null;
  const view = useView.getState();
  const id = freshId('n', Object.keys(doc.canvas.notes));
  const note: CanvasNote = { x: Math.round(at.x), y: Math.round(at.y), text: '', ...extra };
  if (kind && kind !== 'sticky') note.kind = kind;
  if (kind === 'title1') Object.assign(note, { maxW: 1200, size: 24, bold: false }, extra);
  if (!kind || kind === 'sticky') note.w = 240;
  if (view.page && doc.canvas.pages.length > 1 && view.page !== doc.canvas.pages[0]?.id) note.page = view.page;
  doc.updateCanvas((canvas) => ({ ...canvas, notes: { ...canvas.notes, [id]: note } }));
  view.select({ kind: 'objects', boards: [], notes: [id] });
  if (kind === undefined || kind === 'sticky' || kind === 'title1') view.setNoteEdit(id);
  return id;
}

/** The world point at the viewport center. */
export function viewportCenter(): { x: number; y: number } {
  const rect = visibleRect();
  return { x: rect.x + rect.w / 2, y: rect.y + rect.h / 2 };
}

/* -------------------------------- pages --------------------------------- */

/** Adds a page and switches to it. The first page is created implicitly. */
export function addPage(): void {
  const doc = useDocument.getState();
  const pages = doc.canvas.pages.length ? doc.canvas.pages : [{ id: 'p1', name: 'Page 1' }];
  const id = freshId('p', pages.map((p) => p.id));
  const names = new Set(pages.map((p) => p.name));
  let number = pages.length + 1;
  for (let n = 1; ; n++) {
    if (!names.has(`Page ${n}`)) {
      number = n;
      break;
    }
  }
  doc.updateCanvas((canvas) => ({ ...canvas, pages: [...pages, { id, name: `Page ${number}` }] }));
  useView.getState().setPage(id);
}

/** Renames a page. */
export function renamePage(id: string, name: string): void {
  const clean = name.trim().slice(0, 80);
  if (!clean) return;
  useDocument.getState().updateCanvas((canvas) => ({ ...canvas, pages: canvas.pages.map((p) => (p.id === id ? { ...p, name: clean } : p)) }));
}

/**
 * Moves a page to follow `afterId` (`null` = first) in one undo step. The
 * current page stays current. Returns whether the order changed.
 */
export function movePage(id: string, afterId: string | null): boolean {
  const doc = useDocument.getState();
  if (doc.readOnly) return false;
  const before = doc.canvas;
  doc.updateCanvas((canvas) => moveCanvasPage(canvas, id, afterId));
  return useDocument.getState().canvas !== before;
}

/** Moves a page one place up or down the list and says so. */
export function stepPage(id: string, direction: -1 | 1): boolean {
  const pages = useDocument.getState().canvas.pages;
  const at = pages.findIndex((p) => p.id === id);
  const to = at + direction;
  if (at < 0 || to < 0 || to >= pages.length) return false;
  // Moving up lands after the page two places up; moving down, after the next one.
  const after = direction < 0 ? (to === 0 ? null : pages[to - 1]!.id) : pages[to]!.id;
  const moved = movePage(id, after);
  if (moved) announce(direction < 0 ? 'Page moved up' : 'Page moved down');
  return moved;
}

/** Deletes a page with its artboards and notes (undoable). */
export function deletePage(id: string): void {
  const doc = useDocument.getState();
  const { canvas } = doc;
  if (canvas.pages.length <= 1) return;
  const first = canvas.pages[0]!.id;
  const onPage = (item: { page?: string }) => (item.page ?? first) === id;
  const boards = Object.entries(canvas.boards).filter(([, e]) => onPage(e)).map(([p]) => p);
  doc.updateCanvas((c) => {
    const notes = Object.fromEntries(Object.entries(c.notes).filter(([, n]) => !onPage(n)));
    const pages = c.pages.filter((p) => p.id !== id);
    // Items on the old first page move to the new first page implicitly.
    return { ...c, pages, notes };
  });
  if (boards.length) doc.deleteBoards(boards);
  useView.getState().setPage(useDocument.getState().canvas.pages[0]?.id ?? null);
}

