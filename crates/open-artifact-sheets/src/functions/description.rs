//! What a formula may call: each function's name, family, arguments and what it answers, as the page's formula
//! help shows them (`functionDescriptionsJson`). The evaluator reads the same table: an argument's `takes` says how
//! it is evaluated and its `error_in_it` what an error in it does; `answers` says what the call gives back.
//!
//! The table is in order by name, and serializes as it is.

use serde::Serialize;

use super::Family;

/// How an argument is evaluated.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize)]
#[serde(rename_all = "camelCase")]
pub enum Takes {
    /// One value: a range in its place is an error (#VALUE!).
    OneValue,
    /// A range, an array or one value: every cell of it.
    SeveralCells,
    /// Where a reference points (ROW, COLUMN, ROWS, COLUMNS), not what is there.
    OnlyThePlace,
    /// A name the call gives a value to (LET).
    AName,
}

/// What an error in an argument does to the call.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize)]
#[serde(rename_all = "camelCase")]
pub enum ErrorInIt {
    /// The error is the call's answer.
    IsTheAnswer,
    /// Errors in cells the call does not use are passed over (a lookup's other rows).
    MayBePassedOver,
    /// The call catches the error, or may never read it (IFERROR, IF's other branch, ISERROR).
    MayBeCaughtOrNeverRead,
}

/// What a call gives back.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize)]
#[serde(rename_all = "camelCase")]
pub enum Answers {
    OneValue,
    /// One of its arguments, as it came: a range stays a range (IF, CHOOSE, IFERROR, LET).
    AnArgumentAsItCame,
    /// Part of an argument: a cell or a row of a range (INDEX, XLOOKUP).
    PartOfAnArgument,
    /// An array, which spills (FILTER, SORT, UNIQUE, …).
    AnArray,
}

#[derive(Debug, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct Argument {
    pub name: &'static str,
    pub is_optional: bool,
    pub repeats: bool,
    /// Taken but not shown in the formula help.
    pub is_hidden: bool,
    pub takes: Takes,
    pub error_in_it: ErrorInIt,
}

#[derive(Debug, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct Description {
    pub name: &'static str,
    pub family: Family,
    pub description: &'static str,
    /// One of the functions the formula help shows first: the 170 the engine had before the round that brought the
    /// rest.
    pub is_common: bool,
    pub arguments: &'static [Argument],
    pub answers: Answers,
    /// Whether the call may answer #N/A with no #N/A in its arguments (a lookup that finds nothing, NA()).
    pub can_be_not_available_by_itself: bool,
}

#[derive(Serialize)]
struct Descriptions {
    families: &'static [Family],
    functions: &'static [Description],
}

/// The answer to `functionDescriptionsJson`.
pub fn descriptions_json() -> String {
    serde_json::to_string(&Descriptions { families: Family::ALL, functions: DESCRIPTIONS }).expect("the descriptions serialize")
}

/// The description of a function, by its name as a formula spells it (upper case).
pub fn description_of(name: &str) -> Option<&'static Description> {
    DESCRIPTIONS.binary_search_by(|d| d.name.cmp(name)).ok().map(|i| &DESCRIPTIONS[i])
}

const fn arg(name: &'static str, takes: Takes, error_in_it: ErrorInIt) -> Argument {
    Argument { name, is_optional: false, repeats: false, is_hidden: false, takes, error_in_it }
}
const fn optional(a: Argument) -> Argument {
    Argument { is_optional: true, ..a }
}
const fn repeats(a: Argument) -> Argument {
    Argument { repeats: true, ..a }
}
const fn hidden(a: Argument) -> Argument {
    Argument { is_hidden: true, ..a }
}


